def describe(code):
    """One-line description of a D1 code byte."""
    if code == NO_FAULT:
        return "no malfunction"
    if code not in DTCS:
        return "not in this ECU's code table"
    p, mode2, name = DTCS[code]
    if name is None:
        return f"{p} (generic slot, not used on the 1998 Maxima per the FSM)"
    return f"{p} {name} (ECM code {mode2})"
